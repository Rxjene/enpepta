// Generates supabase/migrations/0003_seed_cases.sql from data/seed/*.json so SQL and JSON never drift.
import fs from "node:fs";
import path from "node:path";
import { loadSeedIndustries } from "../src/agent/case-library";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows: string[] = [];
const industries: string[] = [];
const jobRows: string[] = [];
for (const ind of loadSeedIndustries()) {
  industries.push(`insert into industries (name, is_seed) select ${q(ind.industry)}, true where not exists (select 1 from industries where is_seed and name = ${q(ind.industry)});`);
  ind.jobs.forEach((j, i) =>
    jobRows.push(`insert into jobs (industry_id, name, position) select id, ${q(j)}, ${i} from industries where is_seed and name = ${q(ind.industry)} and not exists (select 1 from jobs where industry_id = industries.id and name = ${q(j)});`),
  );
  for (const c of ind.cases) {
    rows.push(
      `(${q(c.industry)}, ${c.year}, ${q(c.job)}, ${q(c.main_driver)}, array[${c.supporting_drivers.map(q).join(",")}]::driver[], ${q(c.stage)}, ${q(c.what_created)}, ${q(c.source)}, ${c.source_url ? q(c.source_url) : "null"}, ${c.approximate})`,
    );
  }
}
const sql = `-- GENERATED by scripts/gen-seed-sql.ts from data/seed/*.json. Do not edit by hand.
${industries.join("\n")}
${jobRows.join("\n")}
insert into cases (industry, year, job, main_driver, supporting_drivers, stage, what_created, source, source_url, approximate) values
${rows.join(",\n")}
on conflict do nothing;
`;
fs.writeFileSync(path.join(__dirname, "../supabase/migrations/0003_seed_cases.sql"), sql);
console.log(`wrote ${rows.length} cases`);
